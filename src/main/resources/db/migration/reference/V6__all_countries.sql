-- The full ISO 3166-1 alpha-2 list, because an operator's postal address now
-- carries a country and three rows (ES/US/DO) cannot address a business.
--
-- flag_key becomes NULLABLE first, and every row added here gets NULL. V2 made
-- it NOT NULL on the reasoning that "the key is the reference, the asset
-- follows" — sound at three rows, false at 249: no flag SVG exists anywhere in
-- this repository, minio-init has no flags/ upload path, and so all three
-- existing keys already resolve to a missing object. Deriving 246 more would
-- have the schema assert that 249 objects exist when zero do, and would put 249
-- broken images on a country picker. MAP's "Country flag assets" backlog slice
-- closes with one UPDATE and a re-tightening SET NOT NULL.
--
-- The ids are literal and derived deterministically from the code
-- (UUIDv3 of "country:{code}"), never gen_random_uuid(): every other reference
-- seed uses literals, and random ids would make dev, staging and prod disagree
-- about what ES is — which makes a country_id in an audit row unresolvable
-- across environments.
--
-- ES, US and DO are deliberately absent. They already exist with hand-written
-- repeating-digit ids that reference.timezones FKs, and restating them with
-- different ids would put a falsehood in this file. ON CONFLICT guards the rest.
--
-- Names are CLDR's English names (java.util.Locale), so they are authoritative
-- rather than hand-typed. They are English only: the storefront exposes the code
-- alongside the name for a client that wants to localize.
ALTER TABLE reference.country
    ALTER COLUMN flag_key DROP NOT NULL;

